import assert from 'node:assert/strict';
import './physics.test.mjs';
import './combat.test.mjs';
import {readFileSync,existsSync} from 'node:fs';
import en from '../src/i18n/en.js';
import fr from '../src/i18n/fr.js';
import {createHash} from 'node:crypto';
for(const [file,entry] of Object.entries(JSON.parse(readFileSync('vendor/checksums.json'))))assert.equal(createHash('sha256').update(readFileSync(file)).digest('hex'),entry.sha256,file);
for(const font of ['fredoka','nunito'])assert.equal(readFileSync(`assets/fonts/${font}.woff2`).subarray(0,4).toString(),'wOF2');
assert.deepEqual(Object.keys(en).sort(),Object.keys(fr).sort());
for(const name of ['LICENSE','ASSETS-BRIEF.md','ASSETS-LICENSE.md','THIRD_PARTY_NOTICES.md','LOB7-GAME.json'])assert(existsSync(name),name);
assert.equal(JSON.parse(readFileSync('LOB7-GAME.json')).entrypoint,'index.html');
console.log('PASS skeleton, legal files, manifest, EN/FR parity');
